
    create table attendance (
        attendance_date date not null,
        created_date date not null,
        id bigint generated by default as identity,
        student_id bigint not null,
        teacher_id bigint not null,
        session enum ('AN','EN','FN') not null,
        status enum ('A','OD','P') not null,
        primary key (id),
        unique (student_id, attendance_date, session),
        check (session IN ('FN','AN','EN') AND status IN ('P','A','OD'))
    );

    create table attendance_unlocks (
        date date not null,
        unlocked boolean not null,
        id bigint generated by default as identity,
        updated_time timestamp(6),
        updated_by varchar(100),
        session enum ('AN','EN','FN') not null,
        primary key (id),
        unique (date, session)
    );

    create table audit_logs (
        id bigint generated by default as identity,
        timestamp timestamp(6) not null,
        device_type varchar(20),
        ip_address varchar(45),
        role varchar(50),
        user_id varchar(100),
        user_email varchar(150) not null,
        action varchar(200) not null,
        entity_name varchar(200),
        primary key (id)
    );

    create table batches (
        active boolean not null,
        id bigint generated by default as identity,
        batch_name varchar(50) not null unique,
        primary key (id)
    );

    create table departments (
        active boolean not null,
        id bigint generated by default as identity,
        department_name varchar(50) not null unique,
        primary key (id)
    );

    create table sections (
        active boolean not null,
        created_at timestamp(6) not null,
        department_id bigint not null,
        id bigint generated by default as identity,
        updated_at timestamp(6) not null,
        section_name varchar(255) not null,
        primary key (id),
        constraint uk_section_name_dept unique (section_name, department_id)
    );

    create table students (
        academic_year integer not null,
        active boolean not null,
        evening_class boolean not null,
        evening_class_enabled boolean not null,
        hosteller boolean not null,
        batch_id bigint not null,
        created_at timestamp(6) not null,
        department_id bigint not null,
        id bigint generated by default as identity,
        section_id bigint,
        updated_at timestamp(6) not null,
        register_number varchar(50) not null unique,
        student_name varchar(255) not null,
        primary key (id)
    );

    create table teachers (
        active boolean not null,
        id bigint generated by default as identity,
        user_id bigint not null unique,
        access_type varchar(50),
        employee_id varchar(50) not null unique,
        designation varchar(100),
        email varchar(100),
        full_name varchar(100),
        primary key (id)
    );

    create table users (
        active boolean not null,
        failed_login_attempts integer not null,
        created_at timestamp(6) not null,
        id bigint generated by default as identity,
        lockout_time timestamp(6),
        updated_at timestamp(6) not null,
        email varchar(100),
        user_id varchar(100) not null unique,
        full_name varchar(255) not null,
        password varchar(255) not null,
        role enum ('ADMIN','TEACHER') not null,
        primary key (id)
    );

    create index idx_student_date 
