    create index idx_register_number 
       on students (register_number);

    create index idx_student_dept 
       on students (department_id);

    create index idx_student_batch 
       on students (batch_id);

    create index idx_teacher_employee 
       on teachers (employee_id);

    create index idx_user_id 
       on users (user_id);

